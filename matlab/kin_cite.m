function out = kin_cite(fmt)
%KIN_CITE  How to cite the kinematics toolbox (doi:10.5281/zenodo.23549236).
%   kin_cite            prints BibTeX
%   kin_cite('text')    prints a plain-text reference
%   s = kin_cite(...)   returns the text instead of printing it
if nargin < 1, fmt = 'bibtex'; end
switch lower(fmt)
    case 'bibtex'
        s = sprintf(['@software{chelidze2026kinematics,\n' ...
            '  author    = {Chelidze, David},\n' ...
            '  title     = {Kinematics toolbox: Model-free differentiation and integration of measured motion},\n' ...
            '  version   = {1.0.0},\n' ...
            '  year      = {2026},\n' ...
            '  publisher = {Zenodo},\n' ...
            '  doi       = {10.5281/zenodo.23549236},\n' ...
            '  url       = {https://github.com/nld-uri/kinematics-toolbox}\n}']);
    case 'text'
        s = ['D. Chelidze, Kinematics toolbox: Model-free differentiation and integration of ' ...
             'measured motion, version 1.0.0, Zenodo (2026). https://doi.org/10.5281/zenodo.23549236'];
    otherwise
        error('kin_cite:fmt', 'fmt must be ''bibtex'' or ''text''.');
end
if nargout, out = s; else, fprintf('%s\n', s); end
end
